  <p class="eyebrow">Koi-Treについて</p>
  <h1>会話の小さな練習室</h1>
  <p>
    初対面やデートで、何を話したらいいか迷うときに。Koi-Treは、AIとの短い会話で自分の伝え方を練習する場所です。
  </p>
  <h2>使い方</h2>
  <p>
    性別を問わず利用できます。初めに男性・女性からお相手を選び、その側の3人の成人キャラクターから選べます。出会い編・デート編・本音編・気持ちを伝える編の4パートで、表情や腕・手のリアクションを見ながら会話できます。ご自身の性別や性的指向を登録する必要はありません。
  </p>
  <ol>
    <li>
      練習したい場面と相手を選ぶか、「練習したい場面を、自分で決める」から状況を書き、Googleアカウントでログインします。
    </li>
    <li>
      キャラクター練習は3往復・6往復から選べます。カスタム練習は3往復です。ご自身の名前・性別・年齢の入力は不要です。
    </li>
    <li>よかった点、改善点、あなたの発言の言い換え例を振り返ります。</li>
  </ol>
  <h2>経験値と物語</h2>
  <p>
    3往復では完了20XP＋ミッション達成10XP、6往復では完了50XP＋ミッション達成20XPを獲得します。100XPごとにレベルが上がり、前のエピソードを終えると次の話が開きます。レベルは練習経験の目安です。過去に獲得した報酬はそのまま残ります。
  </p>
  <p>
    クリア済みのパートには「クリア済みパートを練習」から戻れます。本音編など必要な場面を、その話の時点の関係で再練習できます。物語の進行や選んだ結末は変わらず、元の会話と分析も残ります。
  </p>
  <h2>25点の振り返り</h2>
  <p>
    受け止め・共感、自分の伝え方、キャッチボール、話題のつながり、距離感・配慮の5観点を各5点、合計25点で振り返ります。数値を取得できない観点は0点で埋めません。旧基準の履歴には換算であることを表示します。6往復では全6返答と前半から後半の変化も振り返ります。
  </p>
  <p>
    終えたエピソードとお気に入りのひと言は、思い出アルバムで読み返せます。完了したキャラクター練習では、一度だけひと言を言い直して相手の反応を試せます。元の会話と振り返りは残り、追加の利用枠は消費しません。
  </p>
  <h2>自分の場面をつくるには</h2>
  <p>
    「2回目のデートの帰りに、来週も会う約束をしたい」など、場所・相手との関係・話したいことを500文字以内で書けます。相手の呼び名と最初のひと言は任意です。呼び名には架空の名前を使ってください。最初のひと言を指定しない場合は、あなたから会話を始めます。
  </p>
  <p>
    設定は練習と一緒に保存され、途中再開や同じ場面での再練習に使います。カスタム場面は3往復1枠で、共通の利用枠を使います。物語の進行は変わりません。
  </p>
  <h2>毎月10枠の無料枠について</h2>
  <p>
    最初のAIの返答を正常に保存できた時点で、3往復は1枠、6往復は2枠を使用します。途中で閉じても、同じ練習の続きや振り返りに追加消費はありません。新しくやり直すと別の練習になります。失敗した生成や会話例の閲覧では消費しません。無料枠は毎月1日の日本時間0時に10枠へ更新されます。変更前から消費済みの練習には追加消費はありません。
  </p>
  <p>
    人物別の買い切りルートパックと、本編クリア後の任意の月額Plusを予定しています。現在、有料プランは準備中です。<a
      href="/pricing">料金・遊べる範囲</a
    >で内容を確認できます。
  </p>
  <h2>データの扱い</h2>
  <p>
    ログインにはFirebase
    Authenticationを利用します。Googleのプロフィール情報はアカウント管理のために保存し、会話の初期設定としてAIへ自動送信することはありません。
  </p>
  <p>
    入力した場面設定と会話は返答と振り返りを作るためにDifyへ送信され、練習の再開と振り返りのために設定・会話履歴・結果を保存します。実名、連絡先、相手の個人情報などは入力しないでください。
  </p>
  <p>
    数値評価にはJevを利用し、場面と会話を送信します。キャラクターの交流では、保存済みの会話の一部を次の返答へ引き継ぎます。購入機能はStripeの決済画面を使い、Koi-Treではカード番号を保存しません。
  </p>
  <p>
    利用状況の計測にはGoogle
    Analyticsを利用します。場面設定・会話本文・氏名・メールアドレスは計測イベントに含めません。
  </p>
  <h2>練習のヒント</h2>
  <p>
    AIの反応は実際の相手の気持ちを保証するものではありません。振り返りは会話を試すためのヒントとして、自分に合う言葉を選んでください。
  </p>
